"""PostgreSQL connection and schema handling for application data."""
import os
import re


ORDERED_TABLES = ('documents', 'chunks', 'faqs', 'test_sets', 'test_cases', 'test_runs')


def enabled():
    return bool(os.getenv('RAG_DATABASE_URL'))


def schema_name(name=None):
    name = name or os.getenv('RAG_POSTGRES_SCHEMA', 'public')
    if not re.fullmatch(r'[a-z_][a-z0-9_]{0,62}', name):
        raise ValueError('PostgreSQL schema 名称无效')
    return name


class Row:
    """Support named and positional access used by the application."""
    def __init__(self, names, values):
        self.names = names
        self.values = values

    def keys(self):
        return self.names

    def __getitem__(self, key):
        return self.values[self.names.index(key) if isinstance(key, str) else key]

    def __iter__(self):
        return iter(self.values)

    def __eq__(self, other):
        return isinstance(other, Row) and self.values == other.values


def row_factory(cursor):
    columns = [(index, col.name) for index, col in enumerate(cursor.description or ())
               if col.name != 'storage_order']
    names = tuple(name for _, name in columns)
    return lambda values: Row(names, tuple(values[index] for index, _ in columns))


def statement(sql):
    """Adapt the project’s internal SQL parameter and row-order conventions."""
    sql = re.sub(r'\browid\b', 'storage_order', sql, flags=re.I)
    sql = re.sub(r'\?\s+IS NULL', 'CAST(? AS TEXT) IS NULL', sql, flags=re.I)
    sql = re.sub(r'\bIS\s+\?', 'IS NOT DISTINCT FROM ?', sql, flags=re.I)
    return sql.replace('?', '%s')


class Connection:
    def __init__(self, raw):
        self.raw = raw

    def __enter__(self):
        self.raw.autocommit = False
        return self

    def __exit__(self, exc_type, *_):
        try:
            if exc_type:
                self.raw.rollback()
            else:
                self.raw.commit()
        finally:
            self.raw.autocommit = True

    def execute(self, sql, params=None):
        if sql == 'BEGIN IMMEDIATE':
            sql = 'BEGIN'
        return self.raw.execute(statement(sql), params)

    def executemany(self, sql, params):
        with self.raw.cursor() as cursor:
            cursor.executemany(statement(sql), params)

    def executescript(self, script):
        for sql in script.split(';'):
            sql = sql.strip()
            if sql and sql != 'BEGIN IMMEDIATE':
                sql = sql.replace('INTEGER PRIMARY KEY AUTOINCREMENT', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
                self.execute(sql.replace(' BLOB', ' BYTEA'))

    def lock(self, key):
        self.execute("SELECT pg_advisory_xact_lock(hashtextextended(current_schema() || ':' || ?, 0))", (key,))

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


def connect(schema=None):
    import psycopg
    name = schema_name(schema)
    raw = psycopg.connect(os.environ['RAG_DATABASE_URL'], autocommit=True, row_factory=row_factory,
                          prepare_threshold=None)
    try:
        raw.execute(f'SET search_path TO "{name}"')
    except BaseException:
        raw.close()
        raise
    return Connection(raw)
